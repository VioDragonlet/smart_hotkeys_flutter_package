/// Supported keyboard HID usages. Mouse/media/modifier-only bindings are excluded.
final Map<int, String> supportedHotkeyKeys = Map.unmodifiable({
  for (var i = 0; i < 26; i++) 0x70004 + i: String.fromCharCode(65 + i),
  for (var i = 0; i < 9; i++) 0x7001e + i: '${i + 1}',
  0x70027: '0',
  0x70028: 'Enter',
  0x70029: 'Escape',
  0x7002a: 'Backspace',
  0x7002b: 'Tab',
  0x7002c: 'Space',
  for (var i = 0; i < 12; i++) 0x7003a + i: 'F${i + 1}',
  for (var i = 0; i < 12; i++) 0x70068 + i: 'F${i + 13}',
  0x7002d: '-',
  0x7002e: '=',
  0x7002f: '[',
  0x70030: ']',
  0x70031: '\\',
  0x70033: ';',
  0x70034: "'",
  0x70035: '`',
  0x70036: ',',
  0x70037: '.',
  0x70038: '/',
  0x70049: 'Insert',
  0x7004a: 'Home',
  0x7004b: 'Page Up',
  0x7004c: 'Delete',
  0x7004d: 'End',
  0x7004e: 'Page Down',
  0x7004f: 'Right',
  0x70050: 'Left',
  0x70051: 'Down',
  0x70052: 'Up',
});
