#pragma once
#include <windows.h>

// Keyboard set-1 scan codes to USB HID positions, independent of text layout.
inline int KeyUsage(DWORD vk, DWORD scan, bool extended) {
  if (vk >= VK_F1 && vk <= VK_F24) {
    return 0x70000 | (vk <= VK_F12 ? 0x3a + vk - VK_F1 : 0x68 + vk - VK_F13);
  }
  if (extended) {
    switch (scan) {
      case 0x47: return 0x7004a; case 0x48: return 0x70052;
      case 0x49: return 0x7004b; case 0x4b: return 0x70050;
      case 0x4d: return 0x7004f; case 0x4f: return 0x7004d;
      case 0x50: return 0x70051; case 0x51: return 0x7004e;
      case 0x52: return 0x70049; case 0x53: return 0x7004c;
      case 0x1d: return 0x700e4; case 0x38: return 0x700e6;
      case 0x5b: return 0x700e3; case 0x5c: return 0x700e7;
      default: return 0;
    }
  }
  static const int table[] = {
    0,0x29,0x1e,0x1f,0x20,0x21,0x22,0x23,0x24,0x25,0x26,0x27,0x2d,0x2e,0x2a,0x2b,
    0x14,0x1a,0x08,0x15,0x17,0x1c,0x18,0x0c,0x12,0x13,0x2f,0x30,0x28,0xe0,0x04,0x16,
    0x07,0x09,0x0a,0x0b,0x0d,0x0e,0x0f,0x33,0x34,0x35,0xe1,0x31,0x1d,0x1b,0x06,0x19,
    0x05,0x11,0x10,0x36,0x37,0x38,0xe5,0,0xe2,0x2c
  };
  return scan < sizeof(table)/sizeof(table[0]) && table[scan] ? 0x70000 | table[scan] : 0;
}
